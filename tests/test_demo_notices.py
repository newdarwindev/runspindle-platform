"""Synthetic resource-layout tests; never a Chromium redistribution approval."""

from __future__ import annotations

import copy
import hashlib
import struct
import unittest
from typing import Any
from unittest.mock import patch

from tools.runner_fleet.demo_notices import audit_notice, decode_notice, resource_v5


def notice_fixture() -> tuple[bytes, dict[str, Any]]:
    plain = b"<!-- Generated by licenses.py; do not edit. -->synthetic contract notice"
    compressed = bytes.fromhex(
        "1b4700e88d946ee662844ad793a5fa5008c5a6156c14b379bde5c1061c38d40cb30e07186cc0b195c4c3b4d6390a78be5e43c2222eba22fe975d9c181f25"
    )
    frame = b"\x1e\x9b" + len(plain).to_bytes(6, "little") + compressed
    pak = (
        struct.pack("<IBxxxHH", 5, 1, 1, 0)
        + struct.pack("<HIHI", 38961, 24, 0, 24 + len(frame))
        + frame
    )
    return pak, {
        "resource_id": 38961,
        "pak_sha256": hashlib.sha256(pak).hexdigest(),
        "frame_sha256": hashlib.sha256(frame).hexdigest(),
        "decoded_bytes": len(plain),
        "decoded_sha256": hashlib.sha256(plain).hexdigest(),
    }


class DemoNoticeTests(unittest.TestCase):
    def test_exact_framed_notice_bytes(self) -> None:
        pak, pin = notice_fixture()
        receipt = audit_notice(pak, pin)
        self.assertEqual(receipt["decoded_sha256"], pin["decoded_sha256"])
        scope = receipt["scope"]
        assert isinstance(scope, str)
        self.assertIn("redistribution review remains separate", scope)

    def test_changed_layout_and_missing_resource_rejected(self) -> None:
        pak, pin = notice_fixture()
        for changed in (
            pak[:10],
            b"\x04" + pak[1:],
            pak[:14] + b"\x00\x00\x00\x00" + pak[18:],
        ):
            with self.assertRaises(ValueError):
                resource_v5(changed, pin["resource_id"])
        with self.assertRaises(ValueError):
            resource_v5(pak, 38962)

    def test_changed_hashes_and_size_rejected(self) -> None:
        pak, pin = notice_fixture()
        for key, value in (
            ("pak_sha256", "0" * 64),
            ("frame_sha256", "0" * 64),
            ("decoded_sha256", "0" * 64),
            ("decoded_bytes", 33 * 1024 * 1024),
        ):
            changed = copy.deepcopy(pin)
            changed[key] = value
            with self.assertRaises(ValueError):
                audit_notice(pak, changed)

    def test_missing_decoder_is_unavailable_not_success(self) -> None:
        pak, pin = notice_fixture()
        with patch(
            "tools.runner_fleet.demo_notices.ctypes.util.find_library",
            return_value=None,
        ):
            with self.assertRaises(RuntimeError):
                audit_notice(pak, pin)

    def test_corrupt_brotli_frame_rejected(self) -> None:
        with self.assertRaises(ValueError):
            decode_notice(b"\x1e\x9b" + (8).to_bytes(6, "little") + b"corrupt", 8)
