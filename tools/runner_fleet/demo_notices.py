"""Read exact generated notice resources as data; never execute browser code."""

from __future__ import annotations

import ctypes
import ctypes.util
import hashlib
import struct
from typing import Any

MAX_NOTICE_BYTES = 32 * 1024 * 1024


def resource_v5(data: bytes, resource_id: int) -> bytes:
    if len(data) < 12:
        raise ValueError("truncated PAK header")
    version, encoding, count, aliases = struct.unpack_from("<IBxxxHH", data)
    table_end = 12 + (count + 1) * 6 + aliases * 4
    if version != 5 or encoding not in (0, 1, 2) or table_end > len(data):
        raise ValueError("unsupported or truncated PAK layout")
    entries = [
        struct.unpack_from("<HI", data, 12 + index * 6) for index in range(count + 1)
    ]
    identifiers = [entry[0] for entry in entries[:-1]]
    offsets = [entry[1] for entry in entries]
    if (
        identifiers != sorted(set(identifiers))
        or entries[-1][0] != 0
        or offsets != sorted(offsets)
        or offsets[0] < table_end
        or offsets[-1] != len(data)
    ):
        raise ValueError("invalid PAK resource table")
    alias_identifiers = set(identifiers)
    for index in range(aliases):
        alias, target = struct.unpack_from(
            "<HH", data, 12 + (count + 1) * 6 + index * 4
        )
        if alias in alias_identifiers or target >= count:
            raise ValueError("invalid PAK alias")
        alias_identifiers.add(alias)
    if resource_id not in identifiers:
        raise ValueError("required PAK resource missing")
    index = identifiers.index(resource_id)
    return data[offsets[index] : offsets[index + 1]]


def decode_notice(frame: bytes, expected_size: int) -> tuple[bytes, int]:
    if (
        len(frame) < 9
        or frame[:2] != b"\x1e\x9b"
        or not 0 < expected_size <= MAX_NOTICE_BYTES
        or int.from_bytes(frame[2:8], "little") != expected_size
    ):
        raise ValueError("invalid or unbounded Chromium Brotli frame")
    library = ctypes.util.find_library("brotlidec")
    if library is None:
        raise RuntimeError("libbrotlidec unavailable; notice decoding not performed")
    decoder = ctypes.CDLL(library)
    decode = decoder.BrotliDecoderDecompress
    decode.argtypes = [
        ctypes.c_size_t,
        ctypes.c_void_p,
        ctypes.POINTER(ctypes.c_size_t),
        ctypes.c_void_p,
    ]
    decode.restype = ctypes.c_int
    version = decoder.BrotliDecoderVersion
    version.argtypes = []
    version.restype = ctypes.c_uint32
    source = ctypes.create_string_buffer(frame[8:])
    destination = ctypes.create_string_buffer(expected_size)
    actual_size = ctypes.c_size_t(expected_size)
    if (
        decode(len(frame) - 8, source, ctypes.byref(actual_size), destination) != 1
        or actual_size.value != expected_size
    ):
        raise ValueError("Chromium notice Brotli decoding failed")
    return destination.raw, int(version())


def audit_notice(pak: bytes, pin: dict[str, Any]) -> dict[str, object]:
    if hashlib.sha256(pak).hexdigest() != pin["pak_sha256"]:
        raise ValueError("notice PAK bytes changed")
    frame = resource_v5(pak, pin["resource_id"])
    if hashlib.sha256(frame).hexdigest() != pin["frame_sha256"]:
        raise ValueError("encoded notice frame changed")
    decoded, decoder_version = decode_notice(frame, pin["decoded_bytes"])
    if hashlib.sha256(decoded).hexdigest() != pin["decoded_sha256"]:
        raise ValueError("decoded notice bytes changed")
    if not decoded.startswith(b"<!-- Generated by licenses.py; do not edit. -->"):
        raise ValueError("resource is not generated Chromium notices")
    return {
        "resource_id": pin["resource_id"],
        "decoded_bytes": len(decoded),
        "decoded_sha256": pin["decoded_sha256"],
        "brotli_decoder_version": decoder_version,
        "scope": "matching embedded notice bytes; redistribution review remains separate",
    }
